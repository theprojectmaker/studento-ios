// Copies server/public/call.html into src/lib/call-html.ts so the app can load the call page
// inline (works even when the server's domain is blocked). Run after editing call.html.
const fs = require('fs');
const path = require('path');
const html = fs.readFileSync(path.join(__dirname, '../server/public/call.html'), 'utf8');
const out = '/** Generated by scripts/build-call-html.cjs from server/public/call.html. Do not edit. */\n' + 'export const CALL_HTML = ' + JSON.stringify(html) + ';\n';
fs.writeFileSync(path.join(__dirname, '../src/lib/call-html.ts'), out);
console.log('call-html.ts written', html.length);
