// Pulls every Studento web theme (public/app.js THEMES + js/themes/pack-*.js)
// into plain data for the native app. Run: node scripts/extract-themes.mjs
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import vm from 'node:vm';

const WEB = path.resolve(import.meta.dirname, '../../period-notify/public');
const src = fs.readFileSync(path.join(WEB, 'app.js'), 'utf8');
const a = src.indexOf('const T = ');
const b = src.indexOf('const GROUP_ORDER');
const ctx = { ICONS: new Proxy({}, { get: () => '' }) };
vm.runInNewContext(src.slice(a, b) + '\nthis.OUT = THEMES;', ctx);
const all = [];
for (const [id, t] of Object.entries(ctx.OUT)) all.push({ id, ...t, ...(t.p || {}) });
for (const f of fs.readdirSync(path.join(WEB, 'js/themes'))) {
  const m = await import(pathToFileURL(path.join(WEB, 'js/themes', f)).href);
  for (const [id, t] of Object.entries(m.THEMES)) all.push({ id, group: m.GROUP, ...t, ...(t.p || {}) });
}
const FIELDS = ['id', 'name', 'group', 'bg', 'accent', 'ink', 'glow', 'fonts', 'dialFace', 'dialTick', 'dialInk', 'dialSecond', 'lcdPanel', 'lcdInk', 'numerals'];
const rows = all.map((t) => {
  const o = {};
  for (const k of FIELDS) if (t[k] != null && t[k] !== '') o[k] = t[k];
  o.style = t.dial ? 'dial:' + t.dial : t.board;
  return o;
});
const out = path.resolve(import.meta.dirname, '../src/lib/theme-data.ts');
const NL = String.fromCharCode(10);
fs.writeFileSync(
  out,
  [
    '// Generated by scripts/extract-themes.mjs from tests/period-notify/public (app.js + js/themes). Do not edit.',
    'export interface RawTheme { id: string; name: string; group: string; bg: string; accent: string; style: string; ink?: string; glow?: string; fonts?: string; dialFace?: string; dialTick?: string; dialInk?: string; dialSecond?: string; lcdPanel?: string; lcdInk?: string; numerals?: string }',
    '',
    'export const RAW_THEMES: RawTheme[] = ' + JSON.stringify(rows, null, 1) + ';',
    '',
  ].join(NL)
);
console.log(rows.length, 'themes');
for (const r of rows) console.log([r.id, r.name, r.group, r.style, r.bg, r.accent, r.fonts || ''].join(' | '));
